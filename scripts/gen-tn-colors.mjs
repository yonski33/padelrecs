// TennisRecs on the PadelRecs v3 pages (owner 2026-11-21, wave 2): its own clay accent, accents only, like sim racing's coral
// (scripts/gen-sr-colors.mjs, which this copies). This writes app/thread/tn-colors.css: every v3 rule (thread.css from the
// v7b block on, and rankings-hub.css) that names a padel accent colour, copied under .th-tnv3 (app/thread/shell.tsx adds it on
// tennis) with the colour swapped. Padel's CSS is untouched. Run after changing v3 CSS: node scripts/gen-tn-colors.mjs
import { readFileSync, writeFileSync } from "node:fs";

// TennisRecs' clay (its theme's --green, #a6492a), lightened for highlights so dark text stays readable on it.
const CLAY = "oklch(0.80 0.11 45)", CLAY_SOFT = "oklch(0.97 0.02 45)", CLAY_MID = "oklch(0.92 0.05 45)";
/** Padel v3 accent → tennis accent (upper-cased keys): the lime highlights, the yellow sticker and the squiggle; backgrounds,
 *  ink, dividers and the sentiment colours stay as the v3 pages have them. */
const MAP = {
  "#D4F58B": CLAY, "#C9EE6E": CLAY, "#B9E85A": CLAY, "#FFE45C": CLAY,
  "#EFFADB": CLAY_SOFT, "#F3FBE4": CLAY_SOFT, "#E3F6B5": CLAY_MID, "#D6E8B5": CLAY_MID,
};
const HEX = /#[0-9A-Fa-f]{6}\b/g;
const swap = (s) => s.replace(HEX, h => MAP[h.toUpperCase()] ?? h);
const hits = (s) => (s.match(HEX) ?? []).some(h => MAP[h.toUpperCase()]);

/** Scope a selector list under .th-tnv3: "body:has(.th.th-pr) x" → "body:has(.th.th-tnv3) x" (same weight, later wins), anything else → ".th-tnv3 x"
 *  (a selector that starts with .th / .th.th-pr names the root itself, so it becomes ".th-tnv3"). */
const scope = (sel) => sel.split(/,(?![^(]*\))/).map(x => {
  const s = x.trim();
  if (/^body:has\([^)]*\)/.test(s)) return s.replace(/^body:has\([^)]*\)/, "body:has(.th.th-tnv3)");
  if (/^\.th(\.th-pr)?(?=[\s.:#[>]|$)/.test(s)) return s.replace(/^\.th(\.th-pr)?/, ".th.th-tnv3");
  return `.th-tnv3 ${s}`;
}).join(", ");

/** Top-level rules and one level of @media, as { at, sel, body } with the at-rule's prelude when nested. */
function rules(css) {
  const out = []; let i = 0;
  const clean = css.replace(/\/\*[\s\S]*?\*\//g, "");
  const read = (src, at) => { let j = 0; while (j < src.length) {
    const open = src.indexOf("{", j); if (open < 0) break;
    const head = src.slice(j, open).trim();
    if (head.startsWith("@")) { let depth = 1, k = open + 1; while (depth && k < src.length) { if (src[k] === "{") depth++; else if (src[k] === "}") depth--; k++; }
      if (/^@media/.test(head)) read(src.slice(open + 1, k - 1), head); j = k; continue; }
    const close = src.indexOf("}", open); out.push({ at, sel: head, body: src.slice(open + 1, close).trim() }); j = close + 1; } };
  read(clean, null); void i;
  return out;
}

const thread = readFileSync("app/thread/thread.css", "utf8");
const start = thread.indexOf("/* PadelRecs racket page v7b");
if (start < 0) throw new Error("v7b block not found in thread.css");
const src = [thread.slice(start), readFileSync("app/thread/rankings/rankings-hub.css", "utf8")];
const lines = [];
for (const css of src) for (const r of rules(css)) {
  if (!hits(r.body)) continue;
  const decl = r.body.split(";").map(d => d.trim()).filter(d => d && hits(d)).map(swap).join("; ");
  const rule = `${scope(r.sel)} { ${decl}; }`;
  lines.push(r.at ? `${r.at} { ${rule} }` : rule);
}
writeFileSync("app/thread/tn-colors.css", `/* Generated by scripts/gen-tn-colors.mjs: TennisRecs' colours on the v3 pages (do not edit by hand). */\n${lines.join("\n")}\n`);
console.log(`${lines.length} rules`);
