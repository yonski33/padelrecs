// SimRacingRecs on the PadelRecs v3 pages keeps its own accent (owner 2026-11-21: "use simracing colors", accents only, not
// backgrounds; design_handoff_simracingrecs README "Design tokens": the coral accent). This writes
// app/thread/sr-colors.css: every v3 rule (thread.css from the v7b block on, and rankings-hub.css) that names a padel colour,
// copied under .th-srv3 (app/thread/shell.tsx adds it on simracing) with the colour swapped. Padel's CSS is untouched.
// Run after changing v3 CSS: node scripts/gen-sr-colors.mjs
import { readFileSync, writeFileSync } from "node:fs";

const CORAL = "oklch(0.72 0.18 32)", CORAL_SOFT = "oklch(0.97 0.025 30)", CORAL_MID = "oklch(0.92 0.07 30)";
/** Padel v3 accent → sim racing accent (upper-cased keys). Owner 2026-11-21: accents only (the lime highlights, the yellow
 *  sticker, the squiggle); backgrounds, ink, dividers and the sentiment colours stay as the v3 pages have them. */
const MAP = {
  "#D4F58B": CORAL, "#C9EE6E": CORAL, "#B9E85A": CORAL, "#FFE45C": CORAL,
  "#EFFADB": CORAL_SOFT, "#F3FBE4": CORAL_SOFT, "#E3F6B5": CORAL_MID, "#D6E8B5": CORAL_MID,
};
const HEX = /#[0-9A-Fa-f]{6}\b/g;
const swap = (s) => s.replace(HEX, h => MAP[h.toUpperCase()] ?? h);
const hits = (s) => (s.match(HEX) ?? []).some(h => MAP[h.toUpperCase()]);

/** Scope a selector list under .th-srv3: "body:has(.th.th-pr) x" → "body:has(.th.th-srv3) x" (same weight, later wins), anything else → ".th-srv3 x"
 *  (a selector that starts with .th / .th.th-pr names the root itself, so it becomes ".th-srv3"). */
const scope = (sel) => sel.split(/,(?![^(]*\))/).map(x => {
  const s = x.trim();
  if (/^body:has\([^)]*\)/.test(s)) return s.replace(/^body:has\([^)]*\)/, "body:has(.th.th-srv3)");
  if (/^\.th(\.th-pr)?(?=[\s.:#[>]|$)/.test(s)) return s.replace(/^\.th(\.th-pr)?/, ".th.th-srv3");
  return `.th-srv3 ${s}`;
}).join(", ");

/** Top-level rules and one level of @media, as { at, sel, body } with the at-rule's prelude when nested. */
function rules(css) {
  const out = []; let i = 0;
  const clean = css.replace(/\/\*[\s\S]*?\*\//g, "");
  const read = (src, at) => { let j = 0; while (j < src.length) {
    const open = src.indexOf("{", j); if (open < 0) break;
    const head = src.slice(j, open).trim();
    if (head.startsWith("@")) { let depth = 1, k = open + 1; while (depth && k < src.length) { if (src[k] === "{") depth++; else if (src[k] === "}") depth--; k++; }
      if (/^@media/.test(head)) read(src.slice(open + 1, k - 1), head); j = k; continue; }
    const close = src.indexOf("}", open); out.push({ at, sel: head, body: src.slice(open + 1, close).trim() }); j = close + 1; } };
  read(clean, null); void i;
  return out;
}

const thread = readFileSync("app/thread/thread.css", "utf8");
const start = thread.indexOf("/* PadelRecs racket page v7b");
if (start < 0) throw new Error("v7b block not found in thread.css");
const src = [thread.slice(start), readFileSync("app/thread/rankings/rankings-hub.css", "utf8")];
const lines = [];
for (const css of src) for (const r of rules(css)) {
  if (!r.body.split(";").some(d => hits(d) && !d.includes("--marker"))) continue;
  // The marker highlight stays padel's yellow on every site (owner 2026-11-22), so its rules are left alone.
  const decl = r.body.split(";").map(d => d.trim()).filter(d => d && hits(d) && !d.includes("--marker")).map(swap).join("; ");
  const rule = `${scope(r.sel)} { ${decl}; }`;
  lines.push(r.at ? `${r.at} { ${rule} }` : rule);
}
writeFileSync("app/thread/sr-colors.css", `/* Generated by scripts/gen-sr-colors.mjs: SimRacingRecs' colours on the v3 pages (do not edit by hand). */\n${lines.join("\n")}\n`);
console.log(`${lines.length} rules`);
